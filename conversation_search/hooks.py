from .models.conversation_search_backend_fts import fts_drop_objects


def uninstall_hook(env):
    """Remove every DB object and parameter this module owns."""
    fts_drop_objects(env.cr)
    env["ir.config_parameter"].sudo().search(
        [("key", "=", "conversation_search.backend")]
    ).unlink()
